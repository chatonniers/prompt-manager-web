export function t(key, lang = 'en', ...args) {
  const val = I18N[lang]?.[key] ?? I18N['en'][key] ?? key;
  return typeof val === 'function' ? val(...args) : val;
}

// Translate a catalog label — handles plain strings (legacy) and {en, fr} objects.
// Falls back to `en` if the requested lang has no translation yet.
export function tl(item, lang = 'en') {
  if (!item) return '';
  if (typeof item === 'string') return item;
  return item[lang] || item.en || item.fr || '';
}
